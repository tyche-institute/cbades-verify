def _sigd_multi(pki, sigds):
    """A COSE_Sign with a nil payload and one signer per ``sigd``."""
    sigs = []
    for sigd in sigds:
        pb = cbor2.dumps({**_good(pki), HDR_SIGD: sigd, HDR_CRIT: [HDR_SIGD]})
        tbs = cbor2.dumps(["Signature", b"", pb, b"", b""])
        sigs.append([pb, V.bb_unprotected(pki, pki.ok), V._raw_sign(pki.ok_key, -7, tbs)])
    return cbor2.dumps(cbor2.CBORTag(98, [b"", {}, None, sigs]))


