def _mini(inter_kw=None, signer_kw=None, signer_key=None, inter_nb=T0, inter_na=T1,
          signer_nb=T0, signer_na=T1):
    """Root -> CA -> signer, with options for the CA and the signer."""
    rk, ik = ec.generate_private_key(ec.SECP256R1()), ec.generate_private_key(ec.SECP256R1())
    sk = signer_key or ec.generate_private_key(ec.SECP256R1())
    root = V._cert(V._name("Mini Root"), V._name("Mini Root"), rk, rk, T0, V._t(2036, 1, 1),
                   ca=True)
    ca = V._cert(V._name("Mini CA"), root.subject, ik, rk, inter_nb, inter_na,
                 **{"ca": True, **(inter_kw or {})})
    signer = V._cert(V._name("Mini Signer"), ca.subject, sk, ik, signer_nb, signer_na,
                     **(signer_kw or {}))
    return SimpleNamespace(root=root, root_key=rk, ca=ca, ca_key=ik, signer=signer,
                           signer_key=sk, ok=signer)


