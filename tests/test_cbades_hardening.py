def _crl(issuer, key, entries=(), this_update=V.CRL_THIS_UPDATE, next_update=V.CRL_NEXT_UPDATE,
         exts=()):
    b = (x509.CertificateRevocationListBuilder().issuer_name(issuer.subject)
         .last_update(this_update).next_update(next_update))
    for serial, when, reason in entries:
        e = x509.RevokedCertificateBuilder().serial_number(serial).revocation_date(when)
        if reason is not None:
            e = e.add_extension(x509.CRLReason(reason), critical=False)
        b = b.add_revoked_certificate(e.build())
    for ext, critical in exts:
        b = b.add_extension(ext, critical=critical)
    return b.sign(key, hashes.SHA256())


