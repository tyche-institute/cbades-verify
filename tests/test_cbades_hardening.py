def _with_curve_oid(cert, issuer_key, oid_der: bytes):
    """``cert`` with its P-256 key relabelled to another curve OID, re-signed."""
    p256 = bytes.fromhex("06082a8648ce3d030107")
    tbs = cert.tbs_certificate_bytes
    assert tbs.count(p256) == 1 and len(oid_der) == len(p256)
    tbs = tbs.replace(p256, oid_der)
    sig = issuer_key.sign(tbs, ec.ECDSA(hashes.SHA256()))
    inner = tbs + bytes.fromhex("300a06082a8648ce3d040302") + b"\x03" + \
        bytes([len(sig) + 1]) + b"\x00" + sig
    return x509.load_der_x509_certificate(b"\x30\x82" + len(inner).to_bytes(2, "big") + inner)


