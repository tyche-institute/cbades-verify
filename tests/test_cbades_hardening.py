_RSA_SHA256 = bytes.fromhex("300d06092a864886f70d01010b0500")
_RSA_MD5 = bytes.fromhex("300d06092a864886f70d0101040500")


def _resign_rsa_md5(cert, key):
    """``cert`` signed again by the RSA ``key`` as md5WithRSAEncryption, by
    hand (PKCS #1 v1.5), since no library here signs MD5."""
    ((_, body),) = _der_items(cert.tbs_certificate_bytes)
    assert body.count(_RSA_SHA256) == 1
    tbs = V._tlv(0x30, body.replace(_RSA_SHA256, _RSA_MD5))
    info = bytes.fromhex("3020300c06082a864886f70d020505000410") + hashlib.md5(tbs).digest()
    pn = key.private_numbers()
    n = pn.public_numbers.n
    k = (n.bit_length() + 7) // 8
    em = b"\x00\x01" + b"\xff" * (k - 3 - len(info)) + b"\x00" + info
    sig = pow(int.from_bytes(em, "big"), pn.d, n).to_bytes(k, "big")
    return x509.load_der_x509_certificate(
        V._tlv(0x30, tbs + _RSA_MD5 + V._tlv(0x03, b"\x00" + sig)))


