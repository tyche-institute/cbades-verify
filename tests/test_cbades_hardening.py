def _with_single_extension(resp, rkey, oid: str, value, critical: bool, *, also=None):
    """``resp`` (ECDSA P-256) with one singleExtension on its first
    SingleResponse, re-signed with ``rkey``; the library cannot add
    singleExtensions itself. The first SingleResponse of the OCSP response
    ``also``, if given, is appended as a second one."""
    a1core = pytest.importorskip("asn1crypto.core")
    a1ocsp = pytest.importorskip("asn1crypto.ocsp")
    parsed = a1ocsp.OCSPResponse.load(resp.public_bytes(serialization.Encoding.DER))
    basic = parsed["response_bytes"]["response"].parsed
    tbs = basic["tbs_response_data"]
    if isinstance(value, bytes):
        value = a1core.ParsableOctetString(value)
    tbs["responses"][0]["single_extensions"] = [a1ocsp.SingleResponseExtension(
        {"extn_id": oid, "critical": critical, "extn_value": value})]
    if also is not None:
        other = a1ocsp.OCSPResponse.load(_der(also))["response_bytes"]["response"].parsed
        tbs["responses"].append(a1ocsp.SingleResponse.load(
            other["tbs_response_data"]["responses"][0].dump()))
    tbs_der = tbs.dump(force=True)
    basic["tbs_response_data"] = a1ocsp.ResponseData.load(tbs_der)
    basic["signature"] = rkey.sign(tbs_der, ec.ECDSA(hashes.SHA256()))
    parsed["response_bytes"]["response"] = basic
    return ocsp.load_der_ocsp_response(parsed.dump(force=True))


