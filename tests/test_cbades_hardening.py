def _with(ctx, **kw):
    return dataclasses.replace(ctx, **kw)


def _verdict(data, ctx):
    r = validate_bytes(data, ctx)
    return r.indication, r.subindication


def _der(obj) -> bytes:
    return obj.public_bytes(serialization.Encoding.DER)


def _good(pki):
    return V.bb_protected(pki, pki.ok)


def _sign1_raw(prot_bstr, unprot, key, alg=-7, *, payload=P, attached=True, signed=None):
    sp = payload if signed is None else signed
    tbs = cbor2.dumps(["Signature1", prot_bstr, b"", sp])
    return cbor2.dumps(cbor2.CBORTag(18, [prot_bstr, unprot, payload if attached else None,
                                          V._raw_sign(key, alg, tbs)]))


def _with_raw_entries(prot: dict, extra: bytes, n: int) -> bytes:
    """``prot`` encoded as a CBOR map with ``n`` more raw key/value pairs."""
    enc = cbor2.dumps(prot)
    assert 0xA0 <= enc[0] < 0xB8 - n
    return bytes([enc[0] + n]) + enc[1:] + extra


def _sign_multi(signers, *, body_prot=b"", body_unprot=None, tbs_body=None, payload=P):
    sigs = []
    for prot, unprot, key, alg in signers:
        pb = cbor2.dumps(prot)
        body = body_prot if tbs_body is None else tbs_body
        tbs = cbor2.dumps(["Signature", body, pb, b"", payload])
        sigs.append([pb, unprot, V._raw_sign(key, alg, tbs)])
    return cbor2.dumps(cbor2.CBORTag(98, [body_prot, body_unprot or {}, payload, sigs]))


def _uh(*instances) -> dict:
    return {HDR_UHEADERS: [cbor2.dumps(i) for i in instances]}


