def _ocsp(cert, issuer, rkey, rcert, *, include=True, this_update=V.OCSP_THIS_UPDATE,
          produced=None, revoked=None):
    """``revoked`` is ``(revocation time, reason)``; without it the status is good."""
    when, reason = revoked or (None, None)
    status = ocsp.OCSPCertStatus.REVOKED if revoked else ocsp.OCSPCertStatus.GOOD
    b = (ocsp.OCSPResponseBuilder()
         .add_response(cert=cert, issuer=issuer, algorithm=hashes.SHA256(),
                       cert_status=status, this_update=this_update,
                       next_update=this_update + dt.timedelta(days=7), revocation_time=when,
                       revocation_reason=reason)
         .responder_id(ocsp.OCSPResponderEncoding.HASH, rcert))
    if include:
        b = b.certificates([rcert])
    return V.produced_at(b.sign(rkey, hashes.SHA256()), rkey, produced or this_update)


