def _sigd(**kw):
    s = {1: cbor2.CBORTag(32, SIGD_MECH_BY_URI_HASH), 2: [V.DATA_NAME], 3: -16,
         4: [V.sha256(P)]}
    for k, v in kw.items():
        key = int(k[1:])
        if v is None:
            s.pop(key, None)
        else:
            s[key] = v
    return s


def _sigd_sig(pki, sigd, *, crit=True, signed=b"", extra=None):
    prot = {**_good(pki), HDR_SIGD: sigd, **(extra or {})}
    if crit:
        prot[HDR_CRIT] = [HDR_SIGD]
    return V.sign1(prot, V.bb_unprotected(pki, pki.ok), P, pki.ok_key, -7, attached=False,
                   signed_payload=signed)


