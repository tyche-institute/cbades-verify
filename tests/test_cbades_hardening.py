def test_cli_text_output_escapes_control_characters(cli_set, tmp_path, monkeypatch, capsys):
    from cbades_verify.validate import Result

    d = tmp_path / "in"
    d.mkdir()
    try:
        (d / "P1\nFORGED  VALID.cbor").write_bytes(b"")
    except OSError:
        pytest.skip("the file system does not take this name")
    forged = Result(INVALID, FORMAT_FAILURE, "bad\nOTHER  VALID\x1b[2J")
    monkeypatch.setattr(cli_mod, "validate_file", lambda path, ctx: forged)
    assert main([str(d), *_cli(cli_set)]) == 0
    out = capsys.readouterr().out
    assert out.count("\n") == 1 and "\\x0a" in out and "\\x1b" in out
