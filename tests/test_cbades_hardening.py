_ECDSA_SHA256 = bytes.fromhex("300a06082a8648ce3d040302")
_ECDSA_SHA1 = bytes.fromhex("300906072a8648ce3d0401")


def _resigned(tbs: bytes, key, load, alg_id: bytes, h=None):
    """The certificate or CRL whose to-be-signed part is ``tbs``, with its
    ecdsa-with-SHA256 AlgorithmIdentifier replaced by ``alg_id`` and signed
    with ``key`` over the hash ``h`` (cryptography no longer signs SHA-1)."""
    h = h or hashes.SHA256()
    ((_, body),) = _der_items(tbs)
    assert body.count(_ECDSA_SHA256) == 1
    tbs = V._tlv(0x30, body.replace(_ECDSA_SHA256, alg_id))
    sig = key.sign(hashlib.new(h.name, tbs).digest(), ec.ECDSA(Prehashed(h)))
    return load(V._tlv(0x30, tbs + alg_id + V._tlv(0x03, b"\x00" + sig)))


def _resign_sha1(cert, issuer_key):
    return _resigned(cert.tbs_certificate_bytes, issuer_key, x509.load_der_x509_certificate,
                     _ECDSA_SHA1, hashes.SHA1())


