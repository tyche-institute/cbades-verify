# 1 and true (or 4 and 4.0) are distinct CBOR keys that cbor2 compares as equal
_ONE_AND_TRUE = bytes.fromhex("a2016161f56162")


def _extra_uheader(pki, raw: bytes) -> dict:
    return {HDR_UHEADERS: V.bb_unprotected(pki, pki.ok)[HDR_UHEADERS] + [raw]}


def test_keys_equal_only_as_numbers(pki, ctx):
    nested = bytes.fromhex("a119fde8") + _ONE_AND_TRUE
    data = V.sign1(_good(pki), _extra_uheader(pki, nested), P, pki.ok_key, -7)
    assert _verdict(data, ctx) == (VALID, None)
    # a real duplicate stays a format error wherever it is
    dup = bytes.fromhex("a119fde8a2016161016162")
    data = V.sign1(_good(pki), _extra_uheader(pki, dup), P, pki.ok_key, -7)
    assert _verdict(data, ctx) == (INVALID, FORMAT_FAILURE)
    # in a header map the colliding key is a label that is neither int nor tstr
    data = V.sign1(_good(pki), _extra_uheader(pki, _ONE_AND_TRUE), P, pki.ok_key, -7)
    r = validate_bytes(data, ctx)
    assert (r.indication, r.subindication) == (INVALID, FORMAT_FAILURE)
    assert "neither int nor tstr" in r.detail
    pb = _with_raw_entries(_good(pki), nested[1:], 1)
    data = _sign1_raw(pb, V.bb_unprotected(pki, pki.ok), pki.ok_key)
    assert _verdict(data, ctx) == (INVALID, FORMAT_FAILURE)
    pb = cbor2.dumps(_good(pki))
    sig = V._raw_sign(pki.ok_key, -7, cbor2.dumps(["Signature1", pb, b"", P]))
    unprot = cbor2.dumps(V.bb_unprotected(pki, pki.ok))
    unprot = bytes([unprot[0] + 2]) + unprot[1:] + bytes.fromhex("0441") + b"\x01" + \
        bytes.fromhex("f944004102")
    data = b"\xd2\x84" + cbor2.dumps(pb) + unprot + cbor2.dumps(P) + cbor2.dumps(sig)
    r = validate_bytes(data, ctx)
    assert (r.indication, "neither int nor tstr" in r.detail) == (INVALID, True)


